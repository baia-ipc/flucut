"""
Generate src/report-logo-data.inc, the logo of the HTML report, from the
wide logo of flucut (docs/logo/flucut-banner.png) and its variant for
dark backgrounds (docs/logo/flucut-banner-dark.png): as data URIs (so
that the report stays self-contained) of WebP images, 520 pixels wide
(shown at about half size, sharp on high-resolution screens). From
Lumipore (github.com/baia-ipc/lumipore, scripts/make_report_logo.py),
with the dark variant read from its own file. Requires Pillow.

Usage: make_report_logo.py docs/logo/flucut-banner.png \
         docs/logo/flucut-banner-dark.png > src/report-logo-data.inc
"""
import base64, io, sys
from PIL import Image

WIDTH = 520

def data_uri(path):
  im = Image.open(path).convert("RGBA")
  height = round(im.size[1] * WIDTH / im.size[0])
  buf = io.BytesIO()
  im.resize((WIDTH, height), Image.LANCZOS).save(buf, "WEBP", quality=85,
                                                 method=6)
  return "data:image/webp;base64," + \
         base64.b64encode(buf.getvalue()).decode()

def print_string(name, s):
  print(f"static const char *const {name} =")
  lines = [s[i:i + 72] for i in range(0, len(s), 72)]
  print("\n".join(f'  "{line}"' for line in lines) + ";\n")

def main(light, dark):
  print("/* (c) 2026 Giorgio Gonnella */\n")
  print("/* generated by scripts/make_report_logo.py from the wide logo")
  print("   (docs/logo/flucut-banner.png, flucut-banner-dark.png): do not")
  print("   edit */\n")
  print_string("report_logo", data_uri(light))
  print_string("report_logo_dark", data_uri(dark))

if __name__ == "__main__":
  if len(sys.argv) != 3:
    sys.exit(__doc__)
  main(sys.argv[1], sys.argv[2])
