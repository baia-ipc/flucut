// Screenshots of the sections of a flucut HTML report, for the manual.
// From the manual of Lumipore (github.com/baia-ipc/lumipore,
// docs/manual/figures), unchanged except for this header.
//
// Usage: node screenshot.js REPORT.html OUTDIR NAME=HEADING [NAME=HEADING...]
//
// For each NAME=HEADING, the part of the report from the heading (h1-h3)
// whose text starts with HEADING to the next heading of the same or a
// higher level (with NAME=+HEADING: to the next heading) is saved as
// OUTDIR/NAME.png. NAME=page saves the top of the page (first 900
// pixels), NAME=head the head (logo and run parameters). Requires
// Playwright (with Chromium).
const { chromium } = require('playwright');
const path = require('path');

(async () => {
  const [report, outdir, ...specs] = process.argv.slice(2);
  const browser = await chromium.launch(
    process.env.CHROMIUM ? { executablePath: process.env.CHROMIUM } : {});
  const page = await browser.newPage({ viewport: { width: 1000, height: 900 },
                                       deviceScaleFactor: 2 });
  await page.goto('file://' + path.resolve(report));
  for (const spec of specs) {
    const [name, heading] = spec.split('=');
    const file = path.join(outdir, name + '.png');
    if (heading === 'page') {
      await page.screenshot({ path: file, clip: { x: 0, y: 0, width: 1000,
                                                  height: 900 } });
      console.log(file);
      continue;
    }
    if (heading === 'head') {
      await page.locator('div.head').screenshot({ path: file });
      console.log(file);
      continue;
    }
    const box = await page.evaluate((spec) => {
      const any = spec.startsWith('+');
      const text = any ? spec.slice(1) : spec;
      const hs = Array.from(document.querySelectorAll('h1, h2, h3'));
      const i = hs.findIndex(h => h.textContent.trim().startsWith(text));
      if (i < 0)
        return null;
      const level = any ? 9 : Number(hs[i].tagName[1]);
      const next = hs.slice(i + 1).find(h => Number(h.tagName[1]) <= level);
      const top = hs[i].getBoundingClientRect().top + window.scrollY;
      // the last section ends before the footer ("Generated by Lumipore")
      const footer = Array.from(document.querySelectorAll('p.note')).find(
        p => p.textContent.startsWith('Generated by'));
      const end = next || footer;
      const bottom = end ? end.getBoundingClientRect().top + window.scrollY
                         : document.body.scrollHeight;
      const body = document.body.getBoundingClientRect();
      return { x: body.left, y: top - 8, width: body.width,
               height: bottom - top };
    }, heading);
    if (box === null) {
      console.error('heading not found: ' + heading);
      process.exitCode = 1;
      continue;
    }
    await page.screenshot({ path: file, clip: box, fullPage: true });
    console.log(file);
  }
  await browser.close();
})();
